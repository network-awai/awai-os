export function pickLocale(languages) {
  const list = Array.isArray(languages) ? languages : [languages].filter(Boolean);
  for (const l of list) {
    const lower = String(l).toLowerCase();
    if (lower.startsWith('en')) return 'en';
    if (lower.startsWith('ja')) return 'ja';
  }
  return 'ja';
}

export function translator(locale = 'ja') {
  const dict = MESSAGES[locale === 'en' ? 'en' : 'ja'];
  return (key, params = {}) => {
    let text = dict[key] ?? MESSAGES.ja[key] ?? key;
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
  };
}

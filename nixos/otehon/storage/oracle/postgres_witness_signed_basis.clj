(require '[clojure.string :as str])
(load-string (first (str/split (slurp "nixos/otehon/storage/oracle/postgres_witness_prolly.clj") #"\(case \(first \*command-line-args\*\)" 2)))
(require '[awai.fs.car :as car] '[kotoba.value.codec :as value] '[kotobase.engine.identity :as ident] '[ed25519.sign :as ed])
(def seed (vec (repeat 32 9)))
(def public-key (ed/public-key seed))
(defn ubytes [s] (mapv #(bit-and 255 %) (.getBytes s "UTF-8")))
(defn cid-str [s] (car/cid-str (car/cid-bytes car/codec-raw (mapv #(bit-and 255 %) (.digest (MessageDigest/getInstance "SHA-256") (.getBytes s "UTF-8"))))))
(defn basis-engine [put! get-block]
 (prolly/prolly-engine {:put! put! :get-fn get-block :blind-fn #(str "basis-fixture:" %) :encrypt-fn identity :decrypt-fn identity :digest-fn cid-str}))
(defn encode-block [v] {:cid (value/value-cid v) :bytes (byte-array (map unchecked-byte (value/encode-value v)))})
(defn validate-basis! [get-block envelope expected-public-key]
 (let [{:keys [commit publication signature]} envelope
       _ (ident/logical-commit commit)
       root (cid-str (ident/logical-commit-string commit))
       _ (ident/physical-publication publication)
       _ (ensure! (= root (:logical-commit-root publication)) "logical root mismatch")
       _ (ensure! (= :prolly (:engine-profile publication)) "wrong engine profile")
       _ (ensure! (= 3 (:engine-format publication)) "wrong engine version")
       payload (ident/signature-payload {:logical-commit-root root :issuer "fixture-issuer" :key-id "fixture-key"})
       _ (ensure! (true? (ed/verify expected-public-key (ubytes payload) signature)) "bad basis signature")
       physical (:physical-root publication)
       _ (walk get-block physical limits)
       eng (basis-engine (fn [& _] (throw (ex-info "read only" {}))) get-block)
       state (engine/restore-state eng physical)
       snap (engine/open-snapshot eng state)
       checkpoint (engine/checkpoint eng snap)
       request (:current-request state)]
  (ensure! (= (:database-id commit) (:database-id checkpoint)) "database mismatch")
  (ensure! (= (:epoch commit) (:epoch checkpoint) (:epoch request)) "epoch mismatch")
  (ensure! (= (:logical-checkpoint-root commit) (:logical-checkpoint-root checkpoint)) "checkpoint mismatch")
  (ensure! (= (:tx-root commit) (:tx-root request)) "transaction mismatch")
  {:logical-root root :physical-root physical :state state :engine eng}))
(defn load-envelope [get-block cid]
 (let [bytes (get-block cid)]
  (ensure! bytes "missing signed basis")
  (let [v (value/decode-value bytes)] (ensure! (= cid (value/value-cid v)) "signed basis CID mismatch") v)))
(defn denied? [f] (try (f) false (catch Exception _ true)))
(case (first *command-line-args*)
 "write"
 (do (ensure! (.mkdir (java.io.File. staging)) "staging exists") (store/init! store-path)
  (let [initial (:root (store/read-store store-path))
        _ (#'pg/query! psql service (str "INSERT INTO awai_witness.root(store_id,root) VALUES ('" store-id "',decode('" (#'pg/wire initial) "','hex'));\n"))
        db (backend (verifier nil limits)) tx (blocks/open-transaction db) eng (basis-engine (:put! tx) (:get-fn tx))
        state (engine/empty-state eng "signed-basis-fixture")
        result (engine/transact eng state {:database-id "signed-basis-fixture" :request-id "tx-1" :tx-data [[:db/add "file" :file/name "alpha"]]})
        receipt (:receipt result) checkpoint (engine/checkpoint eng (engine/open-snapshot eng (:state result)))
        commit (ident/logical-commit {:format ident/logical-commit-format :database-id (:database-id receipt) :epoch (:epoch receipt) :parents [] :tx-root (:tx-root receipt) :logical-checkpoint-root (:logical-checkpoint-root checkpoint) :schema-root "fixture-schema" :model-contract-root "fixture-model" :admission-policy-root "fixture-policy"})
        logical-root (cid-str (ident/logical-commit-string commit))
        publication (ident/physical-publication {:format ident/physical-publication-format :logical-commit-root logical-root :engine-profile :prolly :engine-format 3 :physical-root (:physical-root receipt)})
        payload (ident/signature-payload {:logical-commit-root logical-root :issuer "fixture-issuer" :key-id "fixture-key"})
        envelope {:commit commit :publication publication :signature (ed/sign (ed/secret-key! seed) (ubytes payload))}
        block (encode-block envelope)]
   ((:put! tx) (:cid block) (:bytes block))
   (ensure! (:published? ((:publish! tx) "signed-basis" nil (:cid block)
                          (fn [get-block root] (validate-basis! get-block (load-envelope get-block root) public-key) true))) "basis publish failed")
   (let [tx2 (blocks/open-transaction db) eng2 (basis-engine (:put! tx2) (:get-fn tx2))
         next-result (engine/transact eng2 (:state result) {:database-id "signed-basis-fixture" :request-id "tx-2" :tx-data [[:db/retract "file" :file/name "alpha"] [:db/add "file" :file/name "beta"]]})
         alternative (get-in next-result [:receipt :physical-root])]
    (ensure! (:published? ((:publish! tx2) "alternate-data" nil alternative)) "alternate publish failed")
    (spit (str base "/basis.edn") (pr-str {:envelope (:cid block) :physical (:physical-root receipt) :logical logical-root :alternative alternative})))
   (prn {:mode :write :envelope (:cid block) :logical logical-root :physical (:physical-root receipt) :pass true})))
 "read"
 (let [db (backend (verifier nil limits)) ids (edn/read-string (slurp (str base "/basis.edn"))) cid (:cid (storage/-read-ref db "signed-basis"))
       get-block #(storage/get-block db %) envelope (load-envelope get-block cid)
       checked (validate-basis! get-block envelope public-key)]
  (ensure! (= cid (:envelope ids)) "basis ref mismatch")
  (ensure! (= (:physical ids) (:physical-root checked)) "physical mismatch")
  (ensure! (= #{["alpha"]} (names-at (:engine checked) (:state checked) {})) "query mismatch")
  (let [eng (basis-engine (fn [& _] (throw (ex-info "read only" {}))) get-block)
        alternate (engine/restore-state eng (:alternative ids))]
   (ensure! (= #{["beta"]} (names-at eng alternate {})) "alternate root is not a valid different dataset"))
  (ensure! (denied? #(validate-basis! get-block (assoc envelope :signature (vec (repeat 64 0))) public-key)) "bad signature accepted")
  (ensure! (denied? #(validate-basis! get-block (assoc-in envelope [:commit :epoch] 7) public-key)) "altered commit accepted")
  (ensure! (denied? #(validate-basis! get-block (assoc-in envelope [:publication :physical-root] (:alternative ids)) public-key)) "different valid physical root accepted")
  (ensure! (denied? #(validate-basis! get-block envelope (ed/public-key (vec (repeat 32 8))))) "wrong signer accepted")
  (ensure! (denied? #(validate-basis! (fn [x] (when-not (= x (:physical ids)) (get-block x))) envelope public-key)) "missing physical root accepted")
  (prn {:mode :read :query #{["alpha"]} :logical (:logical-root checked) :physical (:physical-root checked) :negative-cases 5 :pass true}))
 (throw (ex-info "write or read required" {})))

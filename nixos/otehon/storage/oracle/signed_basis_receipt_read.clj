(require '[clojure.string :as str] '[clojure.edn :as edn])
(load-file "nixos/otehon/storage/oracle/signed_basis_receipt_common.clj")
(def causal-src (slurp "nixos/otehon/storage/oracle/causal_forest_receipt.clj"))
(load-string (first (str/split (subs causal-src (inc (str/index-of causal-src "\n"))) #"\(def receipt-output")))
(def output-dir (System/getenv "CAUSAL_RECEIPT_OUTPUT"))
(def ack (edn/read-string (slurp (str output-dir "/ids.edn"))))
(reset! forest-handle (catalog/recover-group (str output-dir "/store") "causal-receipt"))
(def recovered (causal/receipt-at (db) (:receipt/commit-cid ack) (:receipt/cid ack)))
(def receipt (first (:receipt/records recovered)))
(def stored-manifest (codec/decode-value (catalog/get-group-block @forest-handle (id/value-cid manifest))))
(def stored-request (codec/decode-value (catalog/get-group-block @forest-handle (id/value-cid request))))
(assert (= manifest stored-manifest))
(assert (= request stored-request))
(assert (= (:receipt/cid ack) (id/value-cid receipt)))
(assert (true? (verifier {:record :execution-receipt :tenant "test" :epoch 7 :payload-cid (id/payload-cid receipt) :signature (:signature receipt)})))
(assert (true? (verifier {:record :execution-manifest :tenant "test" :epoch 7 :payload-cid (id/payload-cid stored-manifest) :signature (:signature stored-manifest)})))
(assert (= (:authority/policy stored-manifest) signed-policy))
(assert (= (id/value-cid manifest) (:execution/manifest receipt)))
(assert (= (id/value-cid request) (:request/digest receipt)))
(assert (= (:data/commit manifest) signed-basis))
(prn {:proof proof-cid :manifest (id/value-cid manifest) :receipt (:receipt/cid ack) :signed-basis-verified true :pass true})
(shutdown-agents)

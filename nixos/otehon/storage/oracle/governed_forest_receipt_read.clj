(require '[clojure.edn :as edn] '[otehon.ipld-forest :as catalog] '[kotoba.value.codec :as codec] '[kotobase.execution-identity :as id] '[kotobase.execution-contract :as contract] '[ed25519.sign :as ed])
(def output-dir (or (System/getenv "RECEIPT_OUTPUT") ".agent-output/receipt"))
(def ids (edn/read-string (slurp (str output-dir "/ids.edn"))))
(def h (catalog/recover-group (str output-dir "/store") "receipt"))
(defn read-block [cid] (let [bytes (catalog/get-group-block h cid) value (codec/decode-value bytes)] (assert (= cid (id/value-cid value))) value))
(def receipt (read-block (:receipt ids)))
(def request (read-block (:request ids)))
(def manifest (read-block (:manifest ids)))
(defn verify [record seed] (ed/verify (ed/public-key (vec (repeat 32 seed))) (mapv #(bit-and 255 %) (.getBytes (id/payload-cid record) "UTF-8")) (get-in record [:signature :signature/value])))
(assert (verify receipt 4))
(assert (verify manifest 3))
(assert (= (:result/root receipt) (:result ids)))
(contract/validate-manifest-request! manifest request)
(assert (= (:request/digest receipt) (:request ids)))
(assert (= (:execution/manifest receipt) (:manifest ids)))
(assert (= :allow (:authority/decision receipt)))
(prn {:receipt (:receipt ids) :result (:result ids) :signatures :verified :manifest-request :bound :pass true})
(shutdown-agents)

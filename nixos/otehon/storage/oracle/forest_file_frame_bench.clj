(require '[otehon.forest :as forest] '[otehon.storage :as store])
(def input-path (System/getenv "FOREST_BENCH_FILE"))
(def file (java.io.File. input-path))
(def digest (first (clojure.string/split (.getName file) #"\.")))
(def start (System/nanoTime))
(def h (assoc (forest/verify-file input-path) :file-backed? true))
(def load-ms (quot (- (System/nanoTime) start) 1000000))
(def read-start (System/nanoTime))
(def total (reduce + (map (fn [b] (let [out (forest/get-block-from h (:cid b) (fn [off len] (first (store/read-payload-segments (.getParent file) digest "forest" (.length file) [{:offset off :length len}]))))] (assert (= (:length b) (alength out))) (alength out))) (butlast (:blocks h)))))
(prn {:verify-ms load-ms :read-ms (quot (- (System/nanoTime) read-start) 1000000) :bytes total :blocks (dec (count (:blocks h))) :pass true})

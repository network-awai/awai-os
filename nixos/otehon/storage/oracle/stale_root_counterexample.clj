;; Local counterexample, not a passing recovery gate. Creates only new data.
(require '[otehon.storage :as store] '[otehon.pack-store :as pack])
(import '[java.nio.file Files Paths CopyOption StandardCopyOption] '[java.security MessageDigest] '[java.util HexFormat])
(def base (or (System/getenv "STALE_ROOT_OUTPUT") (throw (ex-info "output required" {}))))
(defn p [s] (Paths/get s (make-array String 0)))
(defn sha [s] (.formatHex (HexFormat/of) (.digest (MessageDigest/getInstance "SHA-256") (Files/readAllBytes (p s)))))
(assert (.mkdir (java.io.File. base)))
(def store-dir (str base "/store"))
(store/init! store-dir)
(Files/copy (p (str store-dir "/root-1.edn")) (p (str base "/generation-1.saved")) (make-array CopyOption 0))
(pack/put-data! store-dir "file" (.getBytes "old" "UTF-8"))
(def pair-before [(sha (str store-dir "/root-0.edn")) (sha (str store-dir "/root-1.edn"))])
(pack/put-data! store-dir "file" (.getBytes "new" "UTF-8"))
(assert (= "new" (String. ^bytes (pack/read-data (pack/recover store-dir) "file") "UTF-8")))
(Files/copy (p (str store-dir "/root-1.edn")) (p (str base "/generation-3.saved")) (make-array CopyOption 0))
(Files/copy (p (str base "/generation-1.saved")) (p (str store-dir "/root-1.edn"))
            (into-array CopyOption [StandardCopyOption/REPLACE_EXISTING]))
(def pair-after [(sha (str store-dir "/root-0.edn")) (sha (str store-dir "/root-1.edn"))])
(def result (store/read-store store-dir))
(def returned (String. ^bytes (pack/read-data (pack/recover store-dir) "file") "UTF-8"))
(assert (= pair-before pair-after))
(assert (= 2 (get-in result [:root :generation])))
(assert (false? (:degraded? result)))
(assert (= "old" returned))
(prn {:root-pair :identical-to-previous :new-generation 3 :observed-generation 2
      :degraded? false :returned returned :rollback :undetected :counterexample true})

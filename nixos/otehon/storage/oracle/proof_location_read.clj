(require '[clojure.string :as str] '[clojure.edn :as edn])
(load-file "nixos/otehon/storage/oracle/proof_location_common.clj")
(def csrc (slurp "nixos/otehon/storage/oracle/causal_forest_receipt.clj"))
(load-string (first (str/split (subs csrc (inc (str/index-of csrc "\n"))) #"\(def receipt-output")))
(def output-dir (System/getenv "CAUSAL_RECEIPT_OUTPUT"))
(def ack (edn/read-string (slurp (str output-dir "/ids.edn"))))
(reset! forest-handle (catalog/recover-group (str output-dir "/store") "causal-receipt"))
(def recovered (causal/receipt-at (db) (:receipt/commit-cid ack) (:receipt/cid ack)))
(def receipt (first (:receipt/records recovered)))
(def saved-manifest (codec/decode-value (catalog/get-group-block @forest-handle (id/value-cid manifest))))
(def saved-request (codec/decode-value (catalog/get-group-block @forest-handle (id/value-cid request))))
(def saved-location (codec/decode-value (catalog/get-group-block @forest-handle (:location/manifest saved-manifest))))
(assert (= manifest saved-manifest))
(assert (= location saved-location))
(assert (= request saved-request))
(assert (= (:request/digest receipt) (id/value-cid saved-request)))
(assert (manifest-signature-valid? saved-manifest))
(assert (verify-location! saved-manifest saved-location signed-proof-cid signed-basis signed-policy))
(assert (= (:execution/manifest receipt) (id/value-cid saved-manifest)))
(assert (= (:receipt/cid ack) (id/value-cid receipt)))
(assert (true? (verifier {:record :execution-receipt :tenant "test" :epoch 7 :payload-cid (id/payload-cid receipt) :signature (:signature receipt)})))
(prn {:proof signed-proof-cid :location (id/value-cid saved-location) :manifest (id/value-cid saved-manifest)
      :receipt (:receipt/cid ack) :binding :verified :substitution :refused :pass true})
(shutdown-agents)

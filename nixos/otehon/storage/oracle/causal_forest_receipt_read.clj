(require '[clojure.edn :as edn] '[clojure.string :as string])
(load-string (first (string/split (slurp "nixos/otehon/storage/oracle/causal_forest_receipt.clj") #"\(def receipt-output")))
(def output-dir (or (System/getenv "CAUSAL_RECEIPT_OUTPUT") ".agent-output/receipt-sink/output"))
(def ack (edn/read-string (slurp (str output-dir "/ids.edn"))))
(reset! forest-handle (catalog/recover-group (str output-dir "/store") "causal-receipt"))
(def recovered (causal/receipt-at (db) (:receipt/commit-cid ack) (:receipt/cid ack)))
(def receipt (first (:receipt/records recovered)))
(assert (= (:receipt/cid ack) (id/value-cid receipt)))
(assert (= :allow (:authority/decision receipt)))
(assert (true? (verifier {:record :execution-receipt :tenant "test" :epoch 7 :payload-cid (id/payload-cid receipt) :signature (:signature receipt)})))
(assert (= (:base/commit request) (:data/commit manifest)))
(assert (= (id/value-cid request) (:request/digest receipt)))
(assert (= (id/value-cid manifest) (:execution/manifest receipt)))
(prn {:receipt (:receipt/cid ack) :commit (:receipt/commit-cid ack) :signature :verified :pass true})
(shutdown-agents)

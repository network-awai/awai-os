(load-string (first (clojure.string/split (slurp "nixos/otehon/storage/oracle/governed_forest_receipt.clj") #"\(store/init! receipt-dir\)")))
(def calls (atom 0))
(def failed (try (governed/execute! (assoc opts :evaluate! (fn [q d] (swap! calls inc) (evaluate q d)) :commit! (fn [_] (throw (ex-info "storage failed" {}))))) :unexpected-return (catch Exception e (.getMessage e))))
(assert (= "storage failed" failed))
(assert (= 1 @calls))
(def denied-dir (str output-dir "/denied-store"))
(def denied-stage (str output-dir "/denied-stage"))
(store/init! denied-dir)
(def saved (atom nil))
(def denied (try (governed/execute! (assoc opts :authorize! (fn [q] {:allowed? false :projection (set (:find q)) :basis basis :policy-cid pcid}) :evaluate! (fn [& _] (throw (ex-info "must not run" {}))) :commit! (fn [receipt] (let [b (mapv block [receipt request manifest]) cid (:cid (first b))] (writer/put-ipld-blocks! denied-dir "receipt" cid b denied-stage tool) (reset! saved cid) {:receipt/durable? true :receipt/cid cid})))) :unexpected-return (catch Exception e (ex-data e))))
(assert (map? denied))
(assert @saved)
(def rr (codec/decode-value (catalog/get-group-block (catalog/recover-group denied-dir "receipt") @saved)))
(assert (= :deny (:authority/decision rr)))
(assert (nil? (:result/root rr)))
(assert (= @saved (id/value-cid rr)))
(prn {:storage-failure :no-result :evaluation-count @calls :denial :no-evaluation :deny-receipt @saved :pass true})
(shutdown-agents)

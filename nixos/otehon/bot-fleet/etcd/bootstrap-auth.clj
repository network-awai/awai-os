(ns etcd-bootstrap-auth
 (:require [cheshire.core :as j] [clojure.java.shell :as sh] [clojure.string :as s] [clojure.edn :as edn]))
(def credential-root (str (System/getProperty "user.home") "/.itonami/control-plane/etcd/awai-bots-v1"))
(def binary (str (System/getProperty "user.dir") "/.agent-output/etcd-package/etcd-v3.6.14-darwin-arm64/etcdctl"))
(def members (j/parse-string (slurp ".agent-output/etcd-preflight.json") true))
(def endpoints (mapv #(str "https://" (:ip %) ":23979") members))
(def args [binary (str "--endpoints=" (s/join "," endpoints))
           (str "--cacert=" credential-root "/client-ca.pem") (str "--cert=" credential-root "/root.pem")
           (str "--key=" credential-root "/root.key") "--dial-timeout=3s" "--command-timeout=8s"])
(defn call! [& argv]
 (let [r (apply sh/sh (concat args argv))]
  (when-not (zero? (:exit r))
    (spit ".agent-output/etcd-auth-error.log" (:err r))
    (throw (ex-info "authenticated admin step failed; preserve cluster" {:operation (take 2 argv) :exit (:exit r)}))) (:out r)))
(let [status (j/parse-string (call! "--write-out=json" "endpoint" "status") true)
      health (j/parse-string (call! "--write-out=json" "endpoint" "health") true)
      ids (set (map #(str (get-in % [:Status :header :cluster_id])) status))
      auth (j/parse-string (call! "--write-out=json" "auth" "status") true)]
 (assert (= 3 (count health))) (assert (every? :health health)) (assert (= 1 (count ids)))
 (assert (= 3 (count (set (map #(get-in % [:Status :header :member_id]) status)))))
 (spit ".agent-output/etcd-endpoint-status-before-auth.json" (j/generate-string status {:pretty true}))
 (spit ".agent-output/etcd-health-before-auth.json" (j/generate-string health {:pretty true}))
 (when (or (:enabled auth) (seq (s/trim (call! "user" "list"))) (seq (s/trim (call! "role" "list"))))
  (throw (ex-info "unexpected existing auth state; no overwrite" {})))
 (call! "user" "add" "root" "--no-password")
 (call! "role" "add" "root")
 (call! "user" "grant-role" "root" "root")
 (call! "role" "add" "awai-bot-worker")
 (call! "role" "grant-permission" "awai-bot-worker" "read" "/itonami/occurrence/v1/enrollment/" "--prefix")
 (doseq [key ["/itonami/occurrence/v1/cursor/" "/itonami/occurrence/v1/run/"]]
  (call! "role" "grant-permission" "awai-bot-worker" "readwrite" key "--prefix"))
 (call! "role" "add" "awai-bot-observer")
 (call! "role" "grant-permission" "awai-bot-observer" "read" "/itonami/occurrence/v1/" "--prefix")
 (doseq [user ["levi" "benjamin" "joseph" "jun-control"]]
  (call! "user" "add" user "--no-password")
  (call! "user" "grant-role" user "awai-bot-worker"))
 (call! "user" "add" "soshiki-observer" "--no-password")
 (call! "user" "grant-role" "soshiki-observer" "awai-bot-observer")
 (call! "auth" "enable")
 (let [auth-after (j/parse-string (call! "--write-out=json" "auth" "status") true)]
  (assert (:enabled auth-after))
  (spit ".agent-output/etcd-auth-status.json" (j/generate-string auth-after {:pretty true})))
 (spit (str credential-root "/cluster.edn")
       (pr-str {:deployment "AWAI-2795-awai-bots-v1" :version "3.6.14" :cluster-id (first ids)
                :endpoints endpoints :etcdctl binary :ca (str credential-root "/client-ca.pem")}))
 (println "Three member identities healthy; certificate-CN RBAC enabled; worker/observer roles scoped"))

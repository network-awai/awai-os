export function getCopy(locale,key,parameters={}) {
 const selected=UI_COPY[locale]?locale:"ja";
 const pluralKey=typeof parameters.count==="number"&&new Intl.PluralRules(selected).select(parameters.count)==="one"&&UI_COPY[selected][key+"One"]?key+"One":key;
 const template=UI_COPY[selected][pluralKey];
 if(typeof template!=='string') throw new Error(`missing-ui-copy:${key}`);
 return template.replace(/\{([a-zA-Z]+)\}/g,(_,name)=>String(parameters[name]??`{${name}}`));
}

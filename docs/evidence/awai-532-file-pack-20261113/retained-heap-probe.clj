(require '[otehon.pack-store :as p])
(defn gc! [] (dotimes [_ 3] (System/gc) (Thread/sleep 100)))
(defn heap [] (let [r (Runtime/getRuntime)] (- (.totalMemory r) (.freeMemory r))))
(gc!)
(def before (heap))
(def handle (p/recover (first *command-line-args*)))
(gc!)
(def after (heap))
(def indexes (mapcat :index (vals @(:index-cache handle))))
(prn {:before before :after after :delta (- after before) :packs (count @(:index-cache handle))
      :cids (count indexes) :cid-class (.getName (class (:cid (first indexes))))})

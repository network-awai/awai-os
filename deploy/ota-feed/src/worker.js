// awai-ota-feed: the Awai PC pilot OTA feed origin (ota.awai.network).
// Worker, plain JS, no build step. No R2 dependency, ever.
//
// Scope (2026-11-24, measured): this Worker serves ONLY the mutable feed
// index. It never proxies payload bytes:
//   - measured 2026-11-24: a 32 MiB raw yataverse PUT is rejected (HTTP 413)
//     and a CAR-ingested file is not returned by the gateway (dag-pb block
//     only, file path 404), so yataverse cannot distribute OTA payloads;
//   - the payload itself lives at the commit-pinned
//     raw.githubusercontent.com URL carried verbatim in the index (owned
//     by a separate change: pinned raw payload + Updater allowlist).
//
// Contract (android/desktop/pc-ab-device/README.md "Updater feed in the
// release build (AWAI-3064)" + patches/updater-pc-maintenance.patch):
//   - Updater fetches https://ota.awai.network/v1/pc/pilot/{device}/{incr}/builds.json
//     and accepts a package only when its URI matches the Updater's
//     allowlist (https, host allowlist, path prefix). The index it reads
//     lives here.
//   - The mutable index is application/json with Cache-Control: no-store.
//     A withdrawal is an empty []. A channel that was never published
//     also answers [] — there is simply no offer for it.
//   - Index entries carry the payload sha256 and the pinned package URL
//     (plus the fields updater-feed.py make-index generates). The
//     Updater and UpdateEngine verify the signed package on device;
//     nothing here is trusted on the way out.
//
// Serving rules:
//   - well-formed /v1/pc/pilot/{device}/{incr}/builds.json -> 200, the
//     stored bytes (or [] when unpublished/withdrawn);
//   - anything else -> 400, fail-closed before any fetch (this worker
//     has no upstream fetch at all, so an upstream 504 cannot surface;
//     any future block-fetch contract converts it to 404).
//
// yataverse is for <= 16 MiB blocks only (index snapshots, receipts,
// manifests) — never for payloads. It is a distribution cache, never the
// only copy: receipts are state:1 local-durable-readback / storeClass:1
// edge-gateway / retentionUntil:0 with no retention promise, so the
// original ZIP stays on the OTA side (git) and long retention needs a
// separate lease (R1 operator-archive). Ingestion writes are serial
// (60 req/60s, 64 MiB/60s, WAF 10 req/10s per IP; 1-2 puts per build,
// retry with the same request-id). Cost is not committed here: USD unit
// prices, free-tier overage absolutes and GC presence are unknown.
//
// Indexes are small mutable JSON documents committed to this repo in
// src/indexes.js, generated by scripts/publish-index.py (which reuses
// updater-feed.py make-index). Publishing an index is therefore a
// git-reviewed `wrangler deploy` of this Worker. No KV/D1/object store,
// no R2; only the free Worker tier.

import { INDEXES } from "./indexes.js";

export { INDEXES };

const INDEX = /^\/v1\/pc\/pilot\/([A-Za-z0-9_-]{1,64})\/([A-Za-z0-9._-]{1,128})\/builds\.json$/;
const UPPERCASE_HEX = /[A-Z]/;

function reject() {
  return new Response(JSON.stringify({ error: "not-found" }), {
    status: 400,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
      "x-content-type-options": "nosniff",
    },
  });
}

function indexResponse(device, incr, headOnly) {
  const stored = INDEXES[`${device}/${incr}`];
  const body = JSON.stringify(stored === undefined ? [] : stored);
  return new Response(headOnly ? null : body, {
    status: 200,
    headers: {
      "content-type": "application/json",
      "cache-control": "no-store",
      "x-content-type-options": "nosniff",
    },
  });
}

export default {
  async fetch(request) {
    if (!["GET", "HEAD"].includes(request.method)) {
      return new Response(JSON.stringify({ error: "method-not-allowed" }), {
        status: 405,
        headers: {
          "content-type": "application/json; charset=utf-8",
          "cache-control": "no-store",
          "x-content-type-options": "nosniff",
          allow: "GET, HEAD",
        },
      });
    }
    const { pathname } = new URL(request.url);
    const headOnly = request.method === "HEAD";
    // Off-prefix and malformed in-prefix paths are 400 (fail-closed before
    // any fetch — this worker has no upstream fetch at all).
    if (!pathname.startsWith("/v1/pc/pilot/")) return reject();
    if (UPPERCASE_HEX.test(pathname)) return reject();
    const index = INDEX.exec(pathname);
    if (index) return indexResponse(index[1], index[2], headOnly);
    return reject();
  },
};

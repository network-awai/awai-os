#!/usr/bin/env python3.11
"""Generate the pilot feed entry for an already published signed OTA ZIP."""

import argparse
import hashlib
import json
import re
import struct
import subprocess
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
from urllib.parse import urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener
from zipfile import BadZipFile

HERE = Path(__file__).resolve().parent.parent
UPDATER = HERE.parent.parent / "android" / "desktop" / "pc-ab-device" / "updater-feed.py"
RELEASE = "https://github.com/network-awai/awai-os/releases/download"
RAW = "https://raw.githubusercontent.com/network-awai/awai-os"
RELEASE_SIGNING = UPDATER.parents[2] / "release-signing"
ASSET_LIMIT = 2 * 1024**3
RAW_LIMIT = 100 * 1024**2
DEPLOY = "wrangler deploy -c deploy/ota-feed/wrangler.jsonc"
HEADER = "// Generated by scripts/publish-index.py.\nexport const INDEXES = "

spec = spec_from_file_location("updater_feed", UPDATER)
updater = module_from_spec(spec)
spec.loader.exec_module(updater)


class AssetRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        target = urlsplit(newurl)
        if (urlsplit(req.full_url).netloc != "github.com" or target.scheme != "https"
                or target.netloc != "release-assets.githubusercontent.com" or target.fragment):
            raise ValueError("unexpected GitHub release asset redirect")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def validate_artifact(url, filename, sha256, size):
    release = re.fullmatch(rf"{re.escape(RELEASE)}/[A-Za-z0-9][A-Za-z0-9._-]*/{sha256}\.zip", url)
    if release:
        if filename != f"{sha256}.zip":
            raise ValueError("stage the ZIP under its SHA-256 filename before publishing")
        if size >= ASSET_LIMIT:
            raise ValueError("a GitHub release asset must be under 2 GiB")
        return
    if re.fullmatch(rf"{re.escape(RAW)}/[0-9a-fA-F]{{40}}(?:/[A-Za-z0-9._-]+)+", url):
        parts = urlsplit(url).path.split("/")
        if parts[-1] != filename or any(part in (".", "..") for part in parts):
            raise ValueError("raw URL must name the exact ZIP without dot segments")
        if size > RAW_LIMIT:
            raise ValueError("GitHub raw OTA ZIPs are limited to 100 MiB. Use a release asset.")
        return
    raise ValueError("use an exact GitHub release asset or commit-pinned Awai repository raw URL")


def verify_manifest(manifest, signature, filename, sha256, size):
    result = subprocess.run(
        ["node", str(RELEASE_SIGNING / "manifest.mjs"), "verify-ota", str(manifest), str(signature),
         str(RELEASE_SIGNING / "keys/release-2026-11.pub")],
        capture_output=True, text=True,
    )
    if result.returncode:
        raise ValueError("OTA release manifest signature or format verification failed")
    if json.loads(result.stdout) != {filename: {"bytes": size, "sha256": sha256}}:
        raise ValueError("signed OTA manifest differs from the ZIP name, size or signing-record digest")


def verify_asset(url, sha256, size):
    opener = build_opener(AssetRedirect())
    with opener.open(Request(url, headers={"Range": "bytes=0-99"}), timeout=30) as response:
        end = min(size, 100) - 1
        if (response.status != 206 or response.headers.get("Content-Range") != f"bytes 0-{end}/{size}"
                or len(response.read(101)) != end + 1):
            raise ValueError("public release asset did not return the expected byte range and size")
    with opener.open(url, timeout=30) as response:
        if (response.status != 200 or response.headers.get("Content-Length") != str(size)
                or hashlib.file_digest(response, "sha256").hexdigest() != sha256):
            raise ValueError("public release asset differs from the signed ZIP")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ota_zip", type=Path, nargs="?")
    parser.add_argument("--withdraw", action="store_true")
    parser.add_argument("--device", required=True)
    parser.add_argument("--incr", required=True, help="installed build's incremental version in the feed URL")
    parser.add_argument("--artifact-url", help="published GitHub release asset or commit-pinned raw URL")
    parser.add_argument("--manifest", type=Path, help="Awai OS OTA release manifest")
    parser.add_argument("--manifest-signature", type=Path, help="detached signature for the OTA manifest")
    parser.add_argument("--release-type")
    parser.add_argument("--version")
    parser.add_argument("--sha256", help="OTA SHA-256 from the trusted signing record")
    parser.add_argument("--source-build", help="delta source incremental, omitted for a full OTA")
    parser.add_argument("--root", type=Path, default=HERE, help="deploy/ota-feed directory")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", args.device):
        parser.error("invalid device segment")
    if not re.fullmatch(r"[A-Za-z0-9._-]{1,128}", args.incr) or args.incr in (".", ".."):
        parser.error("invalid incremental segment")

    try:
        if args.withdraw:
            if args.ota_zip is not None:
                parser.error("--withdraw does not take a ZIP")
            offers = []
        else:
            if not all((args.ota_zip, args.artifact_url, args.release_type, args.version, args.sha256,
                        args.manifest, args.manifest_signature)):
                parser.error("provide a ZIP, --artifact-url, --release-type, --version, --sha256, "
                             "--manifest and --manifest-signature")
            if not re.fullmatch(r"[0-9a-f]{64}", args.sha256):
                parser.error("--sha256 must be 64 lowercase hex characters")
            size = args.ota_zip.stat().st_size
            url = args.artifact_url
            validate_artifact(url, args.ota_zip.name, args.sha256, size)
            if args.source_build is not None and args.source_build != args.incr:
                parser.error("the delta must be offered at its source incremental feed path")
            verify_manifest(args.manifest, args.manifest_signature, args.ota_zip.name, args.sha256, size)
            offers = updater.make_index(
                args.ota_zip, url, args.sha256, args.device, args.release_type,
                args.version, args.source_build, require_streaming=True,
            )
            verify_asset(url, args.sha256, offers[0]["files"][0]["size"])

        audit = args.root / "indexes" / "indexes.json"
        indexes = json.loads(audit.read_text(encoding="utf-8"))
        indexes[f"{args.device}/{args.incr}"] = offers
        rendered = json.dumps(indexes, indent=2, sort_keys=True)
        if args.dry_run:
            print(rendered)
        else:
            audit.write_text(rendered + "\n", encoding="utf-8")
            (args.root / "src" / "indexes.js").write_text(HEADER + rendered + ";\n", encoding="utf-8")
    except (OSError, ValueError, BadZipFile, KeyError, struct.error) as error:
        parser.exit(1, f"{error}\n")

    print(DEPLOY)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3.11
"""Publish a verified OTA ZIP to the deploy/ota-feed Worker index.

Reproducible path: signed OTA ZIP -> checksum (SHA-256) -> digest-qualified
object path under /v1/pc/pilot/ -> index JSON (via updater-feed.py
make-index, reused unmodified) -> served by the Worker.

This script NEVER deploys and NEVER uploads payload bytes. It writes the
deterministic index files next to itself and then prints the exact
commands for the operator: ingest the payload bytes into the yataverse
network, verify, and deploy the Worker (production deploy needs explicit
owner confirmation).

Payload storage: payload bytes are addressed by their SHA-256 and served
through the yataverse protocol (https://yataverse.com/ipfs/<CIDv1>),
never the Cloudflare object store (policy 2026-11-23). The CID is derived
from the SHA-256, so no data map is maintained.

Requires Python >= 3.11 (hashlib.file_digest, as in updater-feed.py).
"""

import argparse
import base64
import hashlib
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import ZipFile

HERE = Path(__file__).resolve().parent.parent
UPDATER = HERE.parent.parent / "android" / "desktop" / "pc-ab-device" / "updater-feed.py"

spec = spec_from_file_location("updater_feed", UPDATER)
updater = module_from_spec(spec)
spec.loader.exec_module(updater)

HEADER = """// GENERATED by scripts/publish-index.py — do not hand-edit; re-run the
// script (it reuses updater-feed.py make-index and rewrites this file plus
// indexes.json deterministically, keys sorted). The mutable feed index
// for https://ota.awai.network/v1/pc/pilot/{device}/{incr}/builds.json.
// A withdrawal is an empty array."""
ORIGIN = "https://ota.awai.network"


def cid_from_sha256(hex_digest):
    """CIDv1 raw/sha2-256 for a 32-byte SHA-256 digest (43 bytes in, 58 out)."""
    raw = bytes([0x01, 0x55, 0x12, 0x20]) + bytes.fromhex(hex_digest)
    return base64.b32encode(raw).decode().lower().rstrip("=")


def read_incr(ota_zip):
    with ZipFile(ota_zip) as archive:
        raw = archive.read("META-INF/com/android/metadata").decode("utf-8")
    return updater.properties(raw)["post-build-incremental"]


def digest_of(path):
    with path.open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def write_indexes(request, root, dry_run):
    """Render src/indexes.js + indexes.json deterministically (sorted keys)."""
    json_text = updater.json.dumps(request, indent=2, sort_keys=True) + "\n"
    js_text = HEADER + "\nexport const INDEXES = " + json_text.rstrip() + ";\n"
    audit = root / "indexes" / "indexes.json"
    code = root / "src" / "indexes.js"
    for path, text in ((audit, json_text), (code, js_text)):
        if dry_run:
            print(f"would write {path}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
        else:
            print(f"unchanged {path}")
    return json_text


def current_indexes(root):
    code = (root / "src" / "indexes.js").read_text(encoding="utf-8")
    tail = code.split("export const INDEXES = ", 1)[1].rstrip(";\n") + "\n"
    return updater.json.loads(tail)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ota_zip", type=Path, nargs="?", default=None)
    parser.add_argument("--withdraw", action="store_true",
                        help="stop offering updates: set the {device}/{incr} index to []")
    parser.add_argument("--device", required=True, help="feed device segment, e.g. virtio_x86_64")
    parser.add_argument("--incr", required=True, help="feed incr segment (the new build's incremental)")
    parser.add_argument("--release-type")
    parser.add_argument("--version")
    parser.add_argument("--sha256", help="SHA-256 from the trusted signing record (must match the ZIP)")
    parser.add_argument("--source-build", help="OTA source incremental, omitted for a full OTA")
    parser.add_argument("--require-streaming", action="store_true",
                        help="require usable UpdateEngine streaming ranges in the index call")
    parser.add_argument("--root", type=Path, default=HERE, help="deploy/ota-feed directory")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    if args.withdraw:
        indexes = current_indexes(args.root)
        indexes[f"{args.device}/{args.incr}"] = []
        write_indexes(indexes, args.root, args.dry_run)
        print(f"withdrawal published: {args.device}/{args.incr} is now []")
        print("Next steps (operator, production deploy needs owner confirmation):")
        print(f"  1. verify: curl -sS https://ota.awai.network/v1/pc/pilot/{args.device}/{args.incr}/builds.json")
        print("  2. deploy: wrangler deploy -c deploy/ota-feed/wrangler.jsonc")
        return
    if args.ota_zip is None or not args.release_type or not args.version:
        parser.error("OTA ZIP, --release-type and --version are required unless --withdraw")
    with TemporaryDirectory() as scratch:
        scratch = Path(scratch)
        sha = digest_of(args.ota_zip)
        if args.sha256 and args.sha256 != sha:
            raise parser.error(f"SHA-256 differs from the signing record: {sha}")
        if read_incr(args.ota_zip) != args.incr:
            raise parser.error(f"post-build-incremental in the OTA does not match --incr")
        # make-index requires the URL to name the exact OTA ZIP; the object
        # path is digest-qualified, so materialize the verified bytes under
        # that name (a copy, never a rename of the signed artifact).
        named = scratch / f"{sha}.zip"
        named.write_bytes(args.ota_zip.read_bytes())
        url = f"{ORIGIN}/v1/pc/pilot/blobs/{sha}.zip"
        index = updater.make_index(named, url, sha, args.device, args.release_type,
                                   args.version, args.source_build,
                                   require_streaming=args.require_streaming)
        indexes = current_indexes(args.root)
        indexes[f"{args.device}/{args.incr}"] = index
        write_indexes(indexes, args.root, args.dry_run)
    print(f"payload object path: {url}")
    print(f"yataverse CID: {cid_from_sha256(sha)}")
    print("Next steps (operator, production deploy needs owner confirmation):")
    print(f"  1. ingest the ZIP bytes at object path {url}; this Worker serves")
    print("     https://yataverse.com/ipfs/<CID> until then (404 payload-unavailable)")
    print("  2. verify: curl -sS -D- https://ota.awai.network/v1/pc/pilot/"
          f"{args.device}/{args.incr}/builds.json | head -30")
    print(f"     curl -sSI -H 'Range: bytes=0-99' {url} | grep -iE 'HTTP|content-range'")
    print("  3. dry-run locally: (cd deploy/ota-feed && node test/local-check.mjs)")
    print("  4. deploy: wrangler deploy -c deploy/ota-feed/wrangler.jsonc")


if __name__ == "__main__":
    main()
